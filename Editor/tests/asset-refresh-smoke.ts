import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, writeFile, rename, rm, copyFile, readFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { robloxStrategy } from '../src/editor/roblox';

await mkdir(resolve('test-results'), { recursive: true });
const root = await mkdtemp(resolve('test-results/asset-refresh-'));
const parent = join(root, 'project');
await mkdir(parent);
const env: Record<string, string> = { ...process.env, UI_EDITOR_BACKGROUND: '1', UI_EDITOR_USER_DATA: join(root, 'runtime') };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ['.'], env });
try {
  const page = await app.firstWindow();
  page.setDefaultTimeout(10000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await app.evaluate(({ dialog }, parent) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [parent] });
  }, parent);
  await page.getByRole('button', { name: '创建工程', exact: true }).click();
  await page.getByRole('dialog', { name: '创建工程', exact: true }).getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByText('请打开一个工程', { exact: true }).waitFor();
  await page.getByRole('button', { name: '文件', exact: true }).click();
  await page.getByRole('button', { name: '新建界面', exact: true }).click();
  await page.getByRole('textbox', { name: '新界面名称', exact: true }).fill('UnsavedWork');
  await page.getByRole('button', { name: '创建', exact: true }).click();
  await page.getByRole('textbox', { name: '界面名称', exact: true }).fill('UnsavedEdit');
  const workspace = join(parent, 'UIEditorWorkspace');
  const ui = join(workspace, 'interfaces', 'External.json');
  await writeFile(ui, JSON.stringify(robloxStrategy.createDocument()));
  await page.getByRole('button', { name: 'UI 资产 External', exact: true }).waitFor();
  await rename(ui, join(workspace, 'interfaces', 'Renamed.json'));
  await page.getByRole('button', { name: 'UI 资产 Renamed', exact: true }).waitFor();
  await page.getByRole('button', { name: 'UI 资产 External', exact: true }).waitFor({ state: 'detached' });
  await rm(join(workspace, 'interfaces', 'Renamed.json'));
  await page.getByRole('button', { name: 'UI 资产 Renamed', exact: true }).waitFor({ state: 'detached' });
  await page.getByRole('button', { name: '模板参考', exact: true }).click();
  const templates = join(workspace, 'styles', 'templates');
  await mkdir(templates, { recursive: true });
  await writeFile(join(templates, 'ExternalTemplate.json'), JSON.stringify(robloxStrategy.createDocument()));
  await page.getByRole('button', { name: 'UI 资产 ExternalTemplate', exact: true }).waitFor();
  await page.getByRole('button', { name: '图片资产', exact: true }).click();
  await page.getByRole('button', { name: '项目图片', exact: true }).click();
  const images = join(parent, 'ArtSource', 'UI');
  await mkdir(join(images, 'Nested'), { recursive: true });
  await page.getByRole('button', { name: '图片文件夹 Nested', exact: true }).dblclick();
  const image = join(images, 'Nested', 'External.png');
  await copyFile(resolve('src/assets/images/Placeholder.png'), image);
  const card = page.getByRole('button', { name: '图片资产 External', exact: true });
  await card.waitFor();
  const source = await card.locator('img').getAttribute('src');
  await copyFile(resolve('src/assets/images/StudTile.png'), image);
  await page.waitForFunction(source => document.querySelector('[aria-label="图片资产 External"] img')?.getAttribute('src') !== source, source);
  await card.click();
  const meta = JSON.parse(await readFile(`${image}.meta`, 'utf8'));
  meta.tags = ['external-update'];
  await writeFile(`${image}.meta`, JSON.stringify(meta));
  await page.waitForFunction(() => (document.querySelector('[aria-label="图片资产标签"]') as HTMLInputElement)?.value === 'external-update');
  await rm(images, { recursive: true });
  await card.waitFor({ state: 'detached' });
  await mkdir(images);
  await copyFile(resolve('src/assets/images/Placeholder.png'), join(images, 'Recreated.png'));
  await page.getByRole('button', { name: '图片资产 Recreated', exact: true }).waitFor();
  await page.getByText('界面有未保存修改', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'UI 资产', exact: true }).click();
  await page.getByRole('button', { name: '项目UI', exact: true }).click();
  await page.getByRole('button', { name: 'UI 资产 UnsavedEdit（未保存）', exact: true }).waitFor();
  const second = join(root, 'second');
  await mkdir(second);
  await app.evaluate(({ dialog }, parent) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [parent] });
    dialog.showMessageBox = async () => ({ response: 1, checkboxChecked: false });
  }, second);
  await page.getByRole('button', { name: '文件', exact: true }).click();
  await page.getByRole('button', { name: '返回 Hub', exact: true }).click();
  await page.getByRole('button', { name: '创建工程', exact: true }).click();
  await page.getByRole('dialog', { name: '创建工程', exact: true }).getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByText('请打开一个工程', { exact: true }).waitFor();
  await page.evaluate(() => {
    (window as any).assetEvents = [];
    window.projects.onAssetsChanged(event => (window as any).assetEvents.push(event.path));
  });
  await writeFile(join(workspace, 'interfaces', 'OldProject.json'), JSON.stringify(robloxStrategy.createDocument()));
  const nextWorkspace = join(second, 'UIEditorWorkspace');
  await writeFile(join(nextWorkspace, 'interfaces', 'NewProject.json'), JSON.stringify(robloxStrategy.createDocument()));
  await page.getByRole('button', { name: 'UI 资产 NewProject', exact: true }).waitFor();
  const events = await page.evaluate(() => (window as any).assetEvents as string[]);
  assert.ok(events.length > 0);
  assert.ok(events.every(path => path === nextWorkspace), 'old project watchers should be closed');
  assert.deepEqual(errors, []);
  console.log('Asset refresh smoke passed: external UI, templates, folders, image content/meta, deletion and recreation.');
} catch (error) {
  console.error(await (await app.firstWindow()).locator('body').innerText());
  throw error;
} finally { await app.close(); }
